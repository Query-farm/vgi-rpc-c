#!/usr/bin/env python3
"""Generate C Arrow schemas directly from the vgi-rpc reference protocols.

Uses the Arrow C Data Interface to preserve formats, flags, dictionaries, and
metadata. Python is a development dependency only; generated files are shipped.
"""

from __future__ import annotations

import argparse
import dataclasses
import io
import struct
from pathlib import Path

import pyarrow as pa
from pyarrow.cffi import ffi
from vgi_rpc import metadata
from vgi_rpc.introspect import compute_protocol_hash
from vgi_rpc.rpc import rpc_methods
from vgi_rpc.rpc._reflection import MethodInfo, ProtocolList, ProtocolSummary, Reflection, ServiceDescription
from vgi_rpc.rpc._token_identity import Identity


def literal(value):
    if value is None:
        return "NULL"
    if isinstance(value, str):
        value = value.encode()
    return '"' + "".join(chr(b) if 32 <= b < 127 and b not in (34, 92) else f"\\{b:03o}" for b in value) + '"'


def metadata_bytes(ptr):
    if ptr == ffi.NULL:
        return None
    offset = 4
    count = struct.unpack("=i", ffi.buffer(ptr, 4))[0]
    for _ in range(count):
        for _ in range(2):
            length = struct.unpack("=i", ffi.buffer(ptr + offset, 4))[0]
            offset += 4 + length
    return bytes(ffi.buffer(ptr, offset))


def stem(name):
    return "".join(part.title() for part in name.split("_"))


def render(protocols, extra_schemas, header_path, lookup, guard):
    schemas = dict(extra_schemas)
    inventories = []
    for protocol, prefix, constant in protocols:
        methods = rpc_methods(protocol)
        inventories.append((protocol, prefix, constant, methods))
        for name, method in methods.items():
            base = prefix + stem(name)
            schemas[base + "Params"] = method.params_schema
            if method.has_return:
                schemas[base + "Envelope"] = method.result_schema
                payload = getattr(method.result_type, "ARROW_SCHEMA", None)
                if payload is not None:
                    schemas[base + "Result"] = payload
            if method.header_type is not None:
                schemas[base + "Header"] = method.header_type.ARROW_SCHEMA
    h, c = io.StringIO(), io.StringIO()
    h.write(
        f'/* Generated by scripts/generate_protocol.py. DO NOT EDIT. */\n#ifndef {guard}\n#define {guard}\n#include "vgi_rpc/method.h"\n#ifdef __cplusplus\nextern "C" {{\n#endif\n'
    )
    c.write(
        f'/* Generated by scripts/generate_protocol.py. DO NOT EDIT. */\n#include "{header_path}"\n#include "vgi_rpc/schema.h"\n#include <errno.h>\n#include <string.h>\n'
    )
    nodes = {}

    def emit(node):
        children = tuple(emit(node.children[i]) for i in range(node.n_children))
        dictionary = emit(node.dictionary) if node.dictionary != ffi.NULL else None
        key = (
            ffi.string(node.format),
            ffi.string(node.name) if node.name != ffi.NULL else None,
            metadata_bytes(node.metadata),
            int(node.flags),
            children,
            dictionary,
        )
        if key in nodes:
            return nodes[key]
        index = len(nodes)
        nodes[key] = index
        child_ptr = "NULL"
        if children:
            child_ptr = f"children_{index}"
            c.write(
                f"static const struct VgiSchemaNode *const {child_ptr}[] = {{"
                + ", ".join(f"&node_{i}" for i in children)
                + "};\n"
            )
        dictionary_ptr = "NULL" if dictionary is None else f"&node_{dictionary}"
        c.write(
            f"static const struct VgiSchemaNode node_{index} = {{{literal(key[0])}, {literal(key[1])}, {literal(key[2])}, {key[3]}, {len(children)}, {child_ptr}, {dictionary_ptr}}};\n"
        )
        return index

    for name, schema in schemas.items():
        exported = ffi.new("struct ArrowSchema*")
        schema._export_to_c(int(ffi.cast("uintptr_t", exported)))
        try:
            index = emit(exported)
        finally:
            exported.release(exported)
        h.write(f"int VgiSchema{name}(struct ArrowSchema *, struct ArrowError *);\n")
        c.write(
            f"int VgiSchema{name}(struct ArrowSchema *out, struct ArrowError *error) {{\n    return VgiSchemaBuild(&node_{index}, out, error);\n}}\n"
        )
    h.write(f"int {lookup}(const char *, struct ArrowSchema *, struct ArrowError *);\n")
    c.write(
        f"int {lookup}(const char *name, struct ArrowSchema *out, struct ArrowError *error) {{\n    if (!name || !out || out->release) return EINVAL;\n"
    )
    for name in schemas:
        c.write(f'    if (!strcmp(name, "{name}")) return VgiSchema{name}(out, error);\n')
    c.write('    ArrowErrorSet(error, "Unknown RPC schema: %s", name);\n    return ENOENT;\n}\n')
    for protocol, prefix, constant, methods in inventories:
        h.write(
            f"#define VGI_{constant}_NAME {literal(getattr(protocol, 'protocol_name', protocol.__name__))}\n#define VGI_{constant}_VERSION {literal(getattr(protocol, 'protocol_version', ''))}\n#define VGI_{constant}_HASH {literal(compute_protocol_hash(getattr(protocol, 'protocol_name', protocol.__name__), methods))}\nextern const struct VgiMethod VGI_{constant}_METHODS[];\nextern const size_t VGI_{constant}_METHOD_COUNT;\n"
        )
        c.write(f"const struct VgiMethod VGI_{constant}_METHODS[] = {{\n")
        for name, method in methods.items():
            base = prefix + stem(name)
            kind = "STREAM" if method.method_type.value == "stream" else ("UNARY" if method.has_return else "VOID")
            result = f"VgiSchema{base}Envelope" if method.has_return else "NULL"
            payload = f"VgiSchema{base}Result" if base + "Result" in schemas else "NULL"
            header = f"VgiSchema{base}Header" if method.header_type else "NULL"
            stream_kind = (
                "UNKNOWN"
                if kind != "STREAM" or method.is_exchange is None
                else ("EXCHANGE" if method.is_exchange else "PRODUCER")
            )
            c.write(
                f"    {{{literal(name)}, VGI_METHOD_{kind}, VgiSchema{base}Params, {result}, {payload}, {header}, VGI_STREAM_{stream_kind}}},\n"
            )
        c.write(
            f"}};\nconst size_t VGI_{constant}_METHOD_COUNT = sizeof(VGI_{constant}_METHODS)/sizeof(VGI_{constant}_METHODS[0]);\n"
        )
    if guard == "VGI_RPC_GENERATED_PROTOCOL_H":
        for label, names in [
            ("INTROSPECT", ("introspect_token",)),
            ("ISSUE", ("issue_grant",)),
            ("INTROSPECT_ISSUE", ("introspect_token", "issue_grant")),
        ]:
            methods = {n: m for n, m in rpc_methods(Identity).items() if n in names}
            h.write(
                f"#define VGI_IDENTITY_HASH_{label} {literal(compute_protocol_hash(Identity.protocol_name, methods))}\n"
            )
        for name, value in sorted(vars(metadata).items()):
            if name.isupper() and isinstance(value, bytes):
                h.write(f"#define VGI_RPC_{name} {literal(value)}\n")
    h.write("#ifdef __cplusplus\n}\n#endif\n#endif\n")
    return h.getvalue(), c.getvalue()


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--output-dir", type=Path, default=Path(__file__).resolve().parents[1])
    args = parser.parse_args()
    core = {"RpcEmpty": pa.schema([])}
    for typ in (MethodInfo, ProtocolList, ProtocolSummary, ServiceDescription):
        core["Rpc" + typ.__name__] = typ.ARROW_SCHEMA
    header, source = render(
        [(Reflection, "Rpc", "REFLECTION"), (Identity, "Identity", "IDENTITY")],
        core,
        "vgi_rpc/generated/protocol.h",
        "VgiRpcSchemaInit",
        "VGI_RPC_GENERATED_PROTOCOL_H",
    )
    from vgi_rpc.conformance import _types
    from vgi_rpc.conformance._protocol import ConformanceService
    from vgi_rpc.conformance.secondary import Secondary

    extra = {name.strip("_"): value for name, value in vars(_types).items() if isinstance(value, pa.Schema)}
    extra.update(
        {
            name: value.ARROW_SCHEMA
            for name, value in vars(_types).items()
            if isinstance(value, type) and dataclasses.is_dataclass(value) and hasattr(value, "ARROW_SCHEMA")
        }
    )
    ch, cs = render(
        [(ConformanceService, "Conformance", "CONFORMANCE"), (Secondary, "Secondary", "SECONDARY")],
        extra,
        "protocol.h",
        "ConformanceSchemaInit",
        "VGI_RPC_CONFORMANCE_PROTOCOL_H",
    )
    stale = False
    for name, text in [
        ("include/vgi_rpc/generated/protocol.h", header),
        ("src/generated/protocol.c", source),
        ("conformance/protocol.h", ch),
        ("conformance/protocol.c", cs),
    ]:
        path = args.output_dir / name
        if path.exists() and path.read_text() == text:
            continue
        if args.check:
            print("STALE", path)
            stale = True
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text)
    return int(stale)


if __name__ == "__main__":
    raise SystemExit(main())
