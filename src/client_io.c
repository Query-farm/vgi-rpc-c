#define _POSIX_C_SOURCE 200809L
#include <errno.h>
#include <poll.h>
#include <pthread.h>
#include <signal.h>
#include <unistd.h>

#include "client_internal.h"

static int ready(int fd, short events, unsigned seconds) {
    struct pollfd p = {fd, events, 0};
    int timeout = seconds > 2147483U ? 2147483000 : (int)seconds * 1000;
    int rc;
    do rc = poll(&p, 1, timeout);
    while (rc < 0 && errno == EINTR);
    return rc == 0 ? ETIMEDOUT : rc < 0 ? errno : 0;
}
static int read_bytes(struct ArrowIpcInputStream *stream, uint8_t *data, int64_t length,
                      int64_t *read_out, struct ArrowError *error) {
    (void)error;
    struct VgiClient *c = stream->private_data;
    *read_out = 0;
    int fd = fileno(c->input), rc = 0;
    while (!rc && *read_out < length) {
        rc = ready(fd, POLLIN, c->options.timeout_seconds);
        if (rc) break;
        int64_t left = length - *read_out;
        ssize_t n = read(fd, data + *read_out, (size_t)(left > 65536 ? 65536 : left));
        if (n < 0 && (errno == EINTR || errno == EAGAIN)) continue;
        if (n < 0) {
            rc = errno;
            break;
        }
        if (!n) break;
        *read_out += n;
    }
    return rc;
}
static int write_bytes(struct ArrowIpcOutputStream *stream, const void *data, int64_t length,
                       int64_t *written, struct ArrowError *error) {
    (void)error;
    struct VgiClient *c = stream->private_data;
    sigset_t blocked, previous, pending;
    sigemptyset(&blocked);
    sigaddset(&blocked, SIGPIPE);
    int rc = pthread_sigmask(SIG_BLOCK, &blocked, &previous);
    if (rc) return rc;
    sigpending(&pending);
    int already_pending = sigismember(&pending, SIGPIPE);
    int fd = fileno(c->output);
    *written = 0;
    while (!rc && *written < length) {
        rc = ready(fd, POLLOUT, c->options.timeout_seconds);
        if (rc) break;
        int64_t left = length - *written;
        ssize_t n =
            write(fd, (const uint8_t *)data + *written, (size_t)(left > 65536 ? 65536 : left));
        if (n < 0 && (errno == EINTR || errno == EAGAIN)) continue;
        if (n <= 0) {
            rc = n < 0 ? errno : EIO;
            break;
        }
        *written += n;
    }
    /* Consume only the signal generated by this write, preserving the caller's
     * pending signal and mask. Never change the process-wide SIGPIPE handler. */
    if (rc == EPIPE && !already_pending && !sigismember(&previous, SIGPIPE)) {
        sigpending(&pending);
        if (sigismember(&pending, SIGPIPE)) {
            int ignored;
            sigwait(&blocked, &ignored);
        }
    }
    pthread_sigmask(SIG_SETMASK, &previous, NULL);
    return rc;
}
static void input_release(struct ArrowIpcInputStream *stream) { stream->release = NULL; }
static void output_release(struct ArrowIpcOutputStream *stream) { stream->release = NULL; }
int VgiClientInput(struct VgiClient *c, struct ArrowIpcInputStream *out) {
    *out = (struct ArrowIpcInputStream){read_bytes, input_release, c};
    return 0;
}
int VgiClientOutput(struct VgiClient *c, struct ArrowIpcOutputStream *out) {
    *out = (struct ArrowIpcOutputStream){write_bytes, output_release, c};
    return 0;
}
